#region Keyboard Event Contracts

/// <summary>
/// Type of keyboard event forwarded to Ghost Session 2.
/// </summary>
public enum GhostKeyEventKind
{
    /// <summary>Key pressed down (WM_KEYDOWN / WM_SYSKEYDOWN).</summary>
    KeyDown,

    /// <summary>Key released up (WM_KEYUP / WM_SYSKEYUP).</summary>
    KeyUp,

    /// <summary>Unicode character generated by keyboard input (WM_CHAR / WM_SYSCHAR).</summary>
    Char
}

/// <summary>
/// Cross-session payload carrying keyboard events from Host PiP to Session 2.
/// </summary>
public sealed record GhostKeyboardPayload
{
    [JsonPropertyName("event")]
    public string Event { get; init; } = string.Empty;

    [JsonPropertyName("vk")]
    public int VirtualKey { get; init; }

    [JsonPropertyName("scan")]
    public int ScanCode { get; init; }

    [JsonPropertyName("char")]
    public string? Character { get; init; }

    [JsonPropertyName("extended")]
    public bool Extended { get; init; }

    [JsonPropertyName("alt")]
    public bool Alt { get; init; }

    [JsonPropertyName("ctrl")]
    public bool Ctrl { get; init; }

    [JsonPropertyName("shift")]
    public bool Shift { get; init; }

    [JsonPropertyName("timestamp")]
    public long TimestampTicks { get; init; } = DateTime.UtcNow.Ticks;
}

